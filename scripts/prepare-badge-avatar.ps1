[CmdletBinding()]
param(
    [string]$InputPath,
    [string]$MattePath,
    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot

if ([string]::IsNullOrWhiteSpace($InputPath)) {
    $InputPath = Join-Path $repoRoot 'firmware\assets\morgan-portrait.png'
}
if ([string]::IsNullOrWhiteSpace($MattePath)) {
    $MattePath = Join-Path $repoRoot 'firmware\assets\morgan-portrait-matte.png'
}
if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = Join-Path $repoRoot 'firmware\morgan_badge\morgan_avatar_rgb565.h'
}

$InputPath = [IO.Path]::GetFullPath($InputPath)
$MattePath = [IO.Path]::GetFullPath($MattePath)
$OutputPath = [IO.Path]::GetFullPath($OutputPath)
foreach ($requiredPath in @($InputPath, $MattePath)) {
    if (-not (Test-Path -LiteralPath $requiredPath)) {
        throw "Avatar source not found: $requiredPath"
    }
}

Add-Type -AssemblyName System.Drawing

# Framing for the current photo; retune if morgan-portrait.png changes.
$width = 240
$height = 188
$portraitTop = 96
$scale = 0.5
$cropCenterX = 275
$cropTop = 57
$fadeStartRow = 152
$sideFade = 36

function Get-SmoothStep([double]$Edge0, [double]$Edge1, [double]$Value) {
    $t = [Math]::Min(1.0, [Math]::Max(0.0, ($Value - $Edge0) / ($Edge1 - $Edge0)))
    return $t * $t * (3.0 - 2.0 * $t)
}

function New-ScaledCrop([Drawing.Image]$Image, [double]$X, [double]$Y, [double]$CropWidth, [double]$CropHeight) {
    $bitmap = [Drawing.Bitmap]::new($width, $height, [Drawing.Imaging.PixelFormat]::Format24bppRgb)
    $graphics = [Drawing.Graphics]::FromImage($bitmap)
    $attributes = [Drawing.Imaging.ImageAttributes]::new()
    try {
        $graphics.CompositingQuality = [Drawing.Drawing2D.CompositingQuality]::HighQuality
        $graphics.InterpolationMode = [Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $graphics.PixelOffsetMode = [Drawing.Drawing2D.PixelOffsetMode]::HighQuality
        $attributes.SetWrapMode([Drawing.Drawing2D.WrapMode]::TileFlipXY)
        $graphics.DrawImage(
            $Image,
            [Drawing.Rectangle]::new(0, 0, $width, $height),
            [single]$X, [single]$Y, [single]$CropWidth, [single]$CropHeight,
            [Drawing.GraphicsUnit]::Pixel,
            $attributes
        )
    } finally {
        $attributes.Dispose()
        $graphics.Dispose()
    }
    return $bitmap
}

$source = [Drawing.Bitmap]::FromFile($InputPath)
$matte = [Drawing.Bitmap]::FromFile($MattePath)
$photo = $null
$alpha = $null

try {
    $cropWidth = $width / $scale
    $cropHeight = $height / $scale
    $cropX = $cropCenterX - $cropWidth / 2
    $photo = New-ScaledCrop $source $cropX $cropTop $cropWidth $cropHeight
    $alpha = New-ScaledCrop $matte $cropX $cropTop $cropWidth $cropHeight

    $columnWeights = [double[]]::new($width)
    for ($x = 0; $x -lt $width; $x++) {
        $columnWeights[$x] = Get-SmoothStep 0 $sideFade ([Math]::Min($x, $width - 1 - $x))
    }
    $rowWeights = [double[]]::new($height)
    for ($y = 0; $y -lt $height; $y++) {
        $rowWeights[$y] = 1.0 - (Get-SmoothStep $fadeStartRow ($height - 1) $y)
    }

    $contentPixels = 0
    $writer = [IO.StreamWriter]::new($OutputPath, $false, [Text.UTF8Encoding]::new($false))
    try {
        $writer.WriteLine('#pragma once')
        $writer.WriteLine('')
        $writer.WriteLine('#include <Arduino.h>')
        $writer.WriteLine('')
        $writer.WriteLine('// Generated by scripts/prepare-badge-avatar.ps1 from firmware/assets/morgan-portrait.png')
        $writer.WriteLine('// and firmware/assets/morgan-portrait-matte.png.')
        $writer.WriteLine("constexpr int16_t kMorganAvatarTop = $portraitTop;")
        $writer.WriteLine("constexpr uint16_t kMorganAvatarWidth = $width;")
        $writer.WriteLine("constexpr uint16_t kMorganAvatarHeight = $height;")
        $writer.WriteLine('const uint16_t kMorganAvatarRgb565[] PROGMEM = {')

        $valuesOnLine = 0
        for ($y = 0; $y -lt $height; $y++) {
            for ($x = 0; $x -lt $width; $x++) {
                $pixel = $photo.GetPixel($x, $y)
                $weight = $alpha.GetPixel($x, $y).R / 255.0 * $columnWeights[$x] * $rowWeights[$y]
                # Widen before shifting; byte channels silently drop red and green bits.
                $red5 = [int][Math]::Round($pixel.R * $weight) -shr 3
                $green6 = [int][Math]::Round($pixel.G * $weight) -shr 2
                $blue5 = [int][Math]::Round($pixel.B * $weight) -shr 3
                $rgb565 = ($red5 -shl 11) -bor ($green6 -shl 5) -bor $blue5
                if ($rgb565 -ne 0) {
                    $contentPixels++
                }
                if ($valuesOnLine -eq 0) {
                    $writer.Write('  ')
                }
                $writer.Write(('0x{0:X4}' -f $rgb565))
                $valuesOnLine++
                $isLastPixel = $x -eq $width - 1 -and $y -eq $height - 1
                if (-not $isLastPixel) {
                    $writer.Write(',')
                }
                if ($valuesOnLine -eq 12 -or $isLastPixel) {
                    $writer.WriteLine()
                    $valuesOnLine = 0
                } else {
                    $writer.Write(' ')
                }
            }
        }
        $writer.WriteLine('};')
        $writer.WriteLine('// Non-black portrait pixels; the self-test requires at least this many on screen.')
        $writer.WriteLine("constexpr uint32_t kMorganAvatarContentPixels = $contentPixels;")
    } finally {
        $writer.Dispose()
    }
} finally {
    if ($null -ne $photo) {
        $photo.Dispose()
    }
    if ($null -ne $alpha) {
        $alpha.Dispose()
    }
    $matte.Dispose()
    $source.Dispose()
}

$generated = Get-Item -LiteralPath $OutputPath
Write-Output "Generated $($generated.FullName) ($($generated.Length) bytes, ${width}x${height} RGB565 at row $portraitTop, $contentPixels content pixels)."